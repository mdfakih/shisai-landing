/**
 * Renders page 1 of every certificate PDF to WebP so the site can preview
 * documents as images (no iframes, works on mobile). Re-run when PDFs change.
 *   node scripts/render-certificates.mjs
 */
import { getDocument } from 'pdfjs-dist/legacy/build/pdf.mjs';
import sharp from 'sharp';
import { readFile, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';

const docs = [
  ['udyam', 'AAA Print _ Udyam Registration Certificate (1) (2).pdf'],
  ['company', 'SHISAI STEEL INDUSTRIES (5) (2).pdf'],
  ['zed', 'Zed certificate (3) (2).pdf'],
  ['trade', 'znox trademart (2).pdf'],
  ['trademark', 'tri clover trademark certificate (3).pdf'],
];
const SRC = path.resolve('public/certificates');
const OUT = path.resolve('public/certificates/previews');
const WIDTHS = { card: 640, full: 1400 };

for (const [id, file] of docs) {
  const data = new Uint8Array(await readFile(path.join(SRC, file)));
  const pdf = await getDocument({ data, useSystemFonts: true, disableFontFace: false }).promise;
  const page = await pdf.getPage(1);
  const base = page.getViewport({ scale: 1 });
  const scale = WIDTHS.full / base.width;
  const viewport = page.getViewport({ scale });
  const { createCanvas } = await import('@napi-rs/canvas');
  const canvas = createCanvas(Math.ceil(viewport.width), Math.ceil(viewport.height));
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = '#ffffff';
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  await page.render({ canvasContext: ctx, viewport, canvasFactory: undefined }).promise;
  const png = canvas.toBuffer('image/png');
  for (const [tag, width] of Object.entries(WIDTHS)) {
    const out = path.join(OUT, `${id}-${tag}.webp`);
    await sharp(png).resize({ width }).webp({ quality: tag === 'card' ? 74 : 80, effort: 6 }).toFile(out);
    console.log(`${id}-${tag}.webp ${((await stat(out)).size / 1024).toFixed(0)}KB ${Math.round(base.width)}x${Math.round(base.height)}pt`);
  }
  await pdf.destroy();
}
await writeFile(path.join(OUT, 'README.txt'), 'Generated by scripts/render-certificates.mjs. Do not edit by hand.\n');
